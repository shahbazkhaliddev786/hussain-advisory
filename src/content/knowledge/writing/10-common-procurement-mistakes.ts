const text = `Procurement rarely fails because of one dramatic error. More often, small weaknesses early in the process build into delays, complaints and disputes later. These are ten of the most common, and the habits that prevent them.

## 1. Starting without a realistic plan

Timelines that ignore approvals, bidding periods and evaluation time put every later stage under pressure. Build the plan backwards from the date the goods, works or services are needed, and include time for every review.

## 2. Vague or restrictive specifications

Unclear specifications invite bids that cannot be compared. Specifications written around one brand or supplier shut out competition. Describe what you need in terms of function and performance, and accept equivalents.

## 3. Skipping market analysis

Without knowing the market, it is hard to set a sensible budget, choose the right method or judge whether bid prices are reasonable. A short market review before bidding saves time later.

## 4. Choosing the wrong method

A method that does not fit the value, risk or nature of the purchase makes the process slow or, worse, non-compliant. Check the thresholds and conditions in the rules that apply.

## 5. Unclear evaluation criteria

If the bidding document does not say exactly how bids will be evaluated, the evaluation is open to challenge. State every criterion, and how it will be applied, before bids are invited.

## 6. Treating bidders unequally

Answering one bidder’s question privately, or giving one firm extra time, undermines fairness. Share every clarification with all bidders, and extend deadlines for everyone or no one.

## 7. Applying criteria that were not published

Evaluators sometimes add requirements or change weightings during the evaluation. Bids can only be judged against the criteria in the bidding document.

## 8. Weak evaluation reports

A report that records conclusions without reasons is hard to defend. Record how each bid was assessed against each criterion, and why.

## 9. Losing focus after signing

Contracts left to run without monitoring drift on time, cost and quality. Name a contract manager, track milestones, and act on problems early.

## 10. Incomplete records

Missing documents make it impossible to show that the process was fair. Keep a complete procurement file, from the plan to contract closure.

## The common thread

Most of these mistakes share a root: steps taken in a hurry, without the full picture. The guides in the Knowledge Hub cover each stage in more detail, and you can [send PASA a question](/knowledge-hub/ask-pasa) about your own situation.
`

